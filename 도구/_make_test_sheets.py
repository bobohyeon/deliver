def write_csv(path: str, header: list[str], rows: list[tuple]) -> None:
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(header)
        writer.writerows(rows)
    print(f"생성: {path} ({len(rows)}건)")


