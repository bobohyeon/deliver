rows = []
for case_id, case_name, steps in GROUPS:
    for order, (procedure, data, result) in enumerate(steps, start=1):
        rows.append([case_id, case_name, order, procedure, data, DATE, result, "", ""])

with open("단위테스트결과서.csv", "w", encoding="utf-8-sig", newline="") as f:
    writer = csv.writer(f)
    writer.writerow(HEADER)
    writer.writerows(rows)

print(f"생성: 단위테스트결과서.csv ({len(rows)}행)")
ids = sorted({r[0] for r in rows})
for i in ids:
    cases = sorted({r[1] for r in rows if r[0] == i})
    count = sum(1 for r in rows if r[0] == i)
    print(f"  {i}  {count:2}단계  ({' / '.join(cases)})")
